import { afterEach, expect, it, vi } from 'vitest'
import { fireEvent, render, screen, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import App from './App.jsx'

afterEach(() => vi.restoreAllMocks())

it('loads the reference data and updates the summary after editing, adding, and removing products', async () => {
  const user = userEvent.setup()
  render(<App />)
  await user.click(screen.getByRole('button', { name: 'Isi Data Contoh' }))
  const summary = screen.getByRole('region', { name: 'Ringkasan transaksi' })
  expect(within(summary).getAllByText('Rp 396.000')).toHaveLength(2)
  const quantity = screen.getByLabelText('QTY produk 1')
  await user.clear(quantity)
  await user.type(quantity, '2')
  expect(within(summary).getAllByText('Rp 76.000')).toHaveLength(2)
  await user.click(screen.getByRole('button', { name: 'Tambah Produk' }))
  expect(screen.getAllByLabelText(/Nama produk \d/)).toHaveLength(3)
  expect(within(summary).queryByText('Rp 76.000')).toBeNull()
  await user.click(screen.getByRole('button', { name: 'Hapus produk 3' }))
  await user.click(screen.getByRole('button', { name: 'Hapus produk 1' }))
  expect(screen.getByLabelText('Nama produk 1').value).toBe('Es Teh Manis')
  expect(within(summary).getAllByText('Rp 44.000')).toHaveLength(2)
  expect(screen.getByRole('button', { name: 'Hapus produk 1' }).disabled).toBe(true)
})

it('keeps an emptied price invalid and accepts an explicit zero', async () => {
  const user = userEvent.setup()
  render(<App />)
  await user.click(screen.getByRole('button', { name: 'Isi Data Contoh' }))
  const price = screen.getByLabelText('Harga satuan produk 1')
  await user.clear(price)
  await user.tab()
  expect(price.getAttribute('aria-invalid')).toBe('true')
  expect(screen.getByText('Harga satuan wajib diisi')).toBeTruthy()
  expect(within(screen.getByRole('region', { name: 'Ringkasan transaksi' })).getAllByText('—')).toHaveLength(3)
  await user.type(price, '0')
  expect(price.getAttribute('aria-invalid')).toBe('false')
  expect(screen.getAllByText('Rp 44.000').length).toBeGreaterThanOrEqual(2)
})

it('requires the custom method only while Lainnya is selected', async () => {
  const user = userEvent.setup()
  render(<App />)
  await user.click(screen.getByRole('button', { name: 'Isi Data Contoh' }))
  await user.selectOptions(screen.getByLabelText('Metode pembayaran'), 'Lainnya')
  const custom = screen.getByLabelText('Nama metode pembayaran')
  await user.click(custom)
  await user.tab()
  expect(custom.getAttribute('aria-invalid')).toBe('true')
  await user.type(custom, 'Kartu')
  expect(custom.getAttribute('aria-invalid')).toBe('false')
  await user.selectOptions(screen.getByLabelText('Metode pembayaran'), 'Tunai')
  expect(screen.queryByLabelText('Nama metode pembayaran')).toBeNull()
  expect(screen.getAllByText('Rp 396.000').length).toBeGreaterThanOrEqual(2)
})

it('preserves edits when reset is cancelled and restores fresh defaults when confirmed', async () => {
  const user = userEvent.setup()
  const confirm = vi.spyOn(window, 'confirm').mockReturnValue(false)
  const view = render(<App />)
  await user.click(screen.getByRole('button', { name: 'Isi Data Contoh' }))
  await user.click(screen.getByRole('button', { name: 'Reset Form' }))
  expect(screen.getByLabelText('Pelanggan').value).toBe('Yuni')
  confirm.mockReturnValue(true)
  await user.click(screen.getByRole('button', { name: 'Reset Form' }))
  expect(screen.getByLabelText('Pelanggan').value).toBe('')
  expect(screen.getAllByLabelText(/Nama produk \d/)).toHaveLength(1)
  expect(screen.getByLabelText('Harga satuan produk 1').value).toBe('')
  await user.type(screen.getByLabelText('Pelanggan'), 'Draft')
  view.unmount()
  render(<App />)
  expect(screen.getByLabelText('Pelanggan').value).toBe('')
})

it('enforces the 50-item limit in the form and allows adding after removal', () => {
  render(<App />)
  const add = screen.getByRole('button', { name: 'Tambah Produk' })
  for (let i = 1; i < 50; i++) fireEvent.click(add)
  expect(screen.getAllByLabelText(/Nama produk \d/)).toHaveLength(50)
  expect(add.disabled).toBe(true)
  fireEvent.click(screen.getByRole('button', { name: 'Hapus produk 20' }))
  expect(screen.getAllByLabelText(/Nama produk \d/)).toHaveLength(49)
  expect(add.disabled).toBe(false)
})
